# ── Welded model ─────────────────────────────────────────────────────────────
def build_welded_xml(*, for_mjlab: bool) -> str:
  """Return the G3.3 XML text with the fingers welded and the hands contact-free.

  Common to both flavours: the 63-wide ``<keyframe>`` block, the 24 finger
  joints and the 26 hand collision geoms are removed, each foot hull is
  wrapped in a welded ``sensor_{side}_foot_fts`` body and renamed
  ``{side}_foot_collision``, and matching contact excludes are appended. The
  ``<light>`` and the ``floor`` plane are removed too: as an mjlab entity the
  terrain and lighting come from the scene cfg, and for sim2sim the
  ``*_sim2sim.xml`` wrapper adds them back.

  ``for_mjlab=True`` (the ``spec_fn`` path) additionally strips the
  ``<actuator>`` block -- mjlab re-adds actuators from the cfgs and keeping
  the XML ``<motor>`` set would collide on names -- and the ``<option>`` line,
  whose ``integrator`` only triggers a spurious attach-conflict warning
  (mjlab's default integrator is already implicitfast).

  ``for_mjlab=False`` keeps the 32 ``<motor>`` actuators and the
  ``<option>``: this is the standalone robot model written by
  ``scripts/dev/export_4ne1_g3_3_xml.py`` for GMR retargeting and
  ``MuJoCoRobot``.

  The unused ``groundplane``/skybox assets, hull mesh assets and the ``floor``
  default class are left in place: they compile fine and removing them would
  also require rewriting the asset/default tree.
  """
  xml_str = NEURA_4NE1_XML.read_text()
  xml_str = re.sub(r"<keyframe>.*?</keyframe>", "", xml_str, flags=re.DOTALL)
  xml_str = re.sub(r"<light\b[^>]*/>", "", xml_str)
  xml_str = re.sub(r"<geom name=\"floor\"[^>]*/>", "", xml_str)
  if for_mjlab:
    xml_str = re.sub(r"<actuator>.*?</actuator>", "", xml_str, flags=re.DOTALL)
    xml_str = re.sub(r"<option\b[^>]*/>", "", xml_str)
  xml_str, n_joints = re.subn(_FINGER_JOINT_RE, "", xml_str)
  if n_joints != len(FINGER_JOINT_NAMES):
    raise ValueError(
      f"{NEURA_4NE1_XML}: expected to strip {len(FINGER_JOINT_NAMES)} finger "
      f"joints, matched {n_joints} -- did the XML export change finger joint names?"
    )
  xml_str, n_geoms = re.subn(_HAND_COLLISION_GEOM_RE, "", xml_str)
  if n_geoms != _HAND_COLLISION_GEOM_COUNT:
    raise ValueError(
      f"{NEURA_4NE1_XML}: expected to strip {_HAND_COLLISION_GEOM_COUNT} hand "
      f"collision geoms, matched {n_geoms} -- did the XML export change hand geom names?"
    )
  # Wrap each foot hull in a G3.1-style FTS body. Exact string match on the
  # geom line so a re-exported XML fails loudly here.
  for side in ("left", "right"):
    foot_geom = (
      f'<geom mesh="link_{side}_ankle_x_convex_hull" class="collision" '
      f'name="link_{side}_ankle_x_collision" />'
    )
    if xml_str.count(foot_geom) != 1:
      raise ValueError(
        f"{NEURA_4NE1_XML}: expected exactly one {side} foot hull geom line, "
        f"found {xml_str.count(foot_geom)} -- did the XML export change?"
      )
    fts_body = (
      f'<body name="sensor_{side}_foot_fts">'
      f'<inertial pos="0 0 0" mass="1e-06" diaginertia="1e-09 1e-09 1e-09" />'
      f'<geom mesh="link_{side}_ankle_x_convex_hull" class="collision" '
      f'name="{side}_foot_collision" />'
      f"</body>"
    )
    xml_str = xml_str.replace(foot_geom, fts_body)
  # MuJoCo's <exclude> is body-pair based, so the pairs already excluded
  # against link_{side}_ankle_x do not cover a geom that moved onto its child.
  fts_excludes = "".join(
    f'<exclude body1="link_{side}_{other}" body2="sensor_{side}_foot_fts" />'
    for side in ("left", "right")
    for other in ("ankle_y", "shin")
  )
  if xml_str.count("</contact>") != 1:
    raise ValueError(f"{NEURA_4NE1_XML}: expected exactly one <contact> block")
  return xml_str.replace("</contact>", fts_excludes + "</contact>")


def spec_from_xml_string(xml_str: str) -> mujoco.MjSpec:
  """Parse an XML string that lives next to ``neura_4ne1_g3_3.xml``.

  ``MjSpec.from_string`` has no file location to resolve the export's
  ``meshdir="."`` against, so the mesh directory is pinned to the robot
  folder. This avoids writing a temp file into the package directory, which
  would race when several dataset-build workers load the model concurrently.
  """
  spec = mujoco.MjSpec.from_string(xml_str)
  spec.meshdir = str(NEURA_4NE1_DIR)
  return spec


def build_spec() -> mujoco.MjSpec:
  """Welded G3.3 MjSpec for mjlab (no actuators), WITHOUT the contract check."""
  return spec_from_xml_string(build_welded_xml(for_mjlab=True))


def get_spec() -> mujoco.MjSpec:
  """Load the 4NE1 G3.3 MjSpec as a bare robot entity (mjlab ``spec_fn``)."""
  verify_model_contract()
  return build_spec()


def compile_model() -> mujoco.MjModel:
  """Compiled welded model (39 qpos, 70 bodies) for FK / offline tooling."""
  return get_spec().compile()


# ── Model contract ───────────────────────────────────────────────────────────
_CONTRACT_VERIFIED = False


def _model_names(model: mujoco.MjModel, obj: mujoco.mjtObj, count: int) -> tuple[str, ...]:
  return tuple(str(mujoco.mj_id2name(model, obj, i)) for i in range(count))


def _layout_mismatch(label: str, actual: tuple[str, ...], expected: tuple[str, ...]) -> str:
  added = [n for n in actual if n not in set(expected)]
  removed = [n for n in expected if n not in set(actual)]
  return (
    f"{NEURA_4NE1_XML} {label} layout no longer matches the frozen 4NE1 G3.3 "
    f"contract in {__name__}: added={added} removed={removed} "
    f"reordered={not added and not removed}. Motion shards, per-joint config "
    f"arrays and exported policies are indexed by this order -- restore the "
    f"layout in the XML, or update BODY_NAMES/JOINT_NAMES and rebuild every "
    f"4NE1 G3.3 dataset and policy."
  )


def verify_model_contract() -> None:
  """Compile the welded G3.3 model and assert its frozen layout.

  Checks the welded model's bodies, hinge joints and qpos layout against
  :data:`BODY_NAMES` / :data:`JOINT_NAMES`, and the raw export's actuator
  order (the welded mjlab spec has no actuators; mjlab adds them from the
  cfgs, but ``MuJoCoRobot`` and the exported sim2sim XML rely on the raw
  ``<motor>`` order). Raises ``ValueError`` naming the first mismatch so a
  model swap surfaces here instead of as silently misindexed motion or
  action arrays.
  """
  global _CONTRACT_VERIFIED
  if _CONTRACT_VERIFIED:
    return

  model = build_spec().compile()
  bodies = _model_names(model, mujoco.mjtObj.mjOBJ_BODY, model.nbody)[1:]
  joints = tuple(
    str(mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_JOINT, i))
    for i in range(model.njnt)
    if model.jnt_type[i] != mujoco.mjtJoint.mjJNT_FREE
  )
  for label, actual, expected in (("body", bodies, BODY_NAMES), ("joint", joints, JOINT_NAMES)):
    if actual != expected:
      raise ValueError(_layout_mismatch(label, actual, expected))
  if model.nq != FULL_QPOS_DIM:
    raise ValueError(
      f"{NEURA_4NE1_XML} welded model has nq={model.nq}, expected {FULL_QPOS_DIM} "
      f"(freejoint(7) + {NUM_JOINTS} hinges)."
    )
  qpos_addr = [
    int(model.jnt_qposadr[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, name)])
    for name in JOINT_NAMES
  ]
  if qpos_addr != list(range(7, FULL_QPOS_DIM)):
    raise ValueError(
      f"{NEURA_4NE1_XML}: JOINT_NAMES do not occupy qpos[7:{FULL_QPOS_DIM}] "
      f"contiguously (got {qpos_addr})."
    )
  for name in FOOT_CONTACT_GEOM_NAMES:
    if mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, name) < 0:
      raise ValueError(f"{NEURA_4NE1_XML} welded model has no geom {name!r}")

  raw_spec = mujoco.MjSpec.from_file(str(NEURA_4NE1_XML))
  actuators = tuple(str(a.target) for a in raw_spec.actuators)
  if actuators != JOINT_NAMES:
    raise ValueError(_layout_mismatch("actuator", actuators, JOINT_NAMES))
  _CONTRACT_VERIFIED = True
