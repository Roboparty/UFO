# Contact point set for the dataset ground alignment (``clip_min_sole``): the
# vertices of the compiled foot collision hulls in the ``link_{side}_ankle_x``
# body frame (the FTS body is welded with an identity transform, so hull frame
# == ankle_x frame). G3.3 has no sole pads -- the whole convex hull is the
# terrain-contact geometry, so its vertex set (not just the flat bottom face,
# z=-0.0835) is what bounds the lowest world point of a pitched or rolled foot:
# the toe tip reaches x=0.205 at z=-0.068 and the heel x=-0.114 at z=-0.018.
# ``_min_sole_world_z`` takes the minimum over all points per frame, so heel/toe
# contact is handled exactly. Generated table, see ``foot_contact_points.py``.
