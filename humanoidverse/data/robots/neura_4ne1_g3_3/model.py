"""Neura 4NE1 G3.3 MuJoCo model contract.

Shared by the two G3.3 actuator-parameter variants
(:mod:`neura_4ne1_g3_3_constants` and :mod:`neura_4ne1_g3_3_constants_sysid`):
the robot XML, the finger-welding transform that turns the 56-hinge CAD export
into the 32-DOF locomotion model, and the frozen body/joint layout that motion
shards, per-joint config arrays and exported policies are indexed by.

Model facts
-----------
* ``neura_4ne1_g3_3.xml`` is a standalone scene generated from
  ``neura_4ne1_g3_3.urdf`` via ``config/g3_3.yaml`` + postprocess: one
  freejoint + 56 hinges (32 body joints + 24 finger joints), 32 ``<motor>``
  actuators for the body joints only, a floor, a light and a 63-wide
  ``standing`` keyframe.
* The motion data for this robot (``robot_retargeter`` output: headerless
  39-column CSVs = root pos 3 + root quat xyzw 4 + 32 joints) and every 4NE1
  policy exclude the fingers, so all consumers -- mjlab training, dataset FK,
  GMR retargeting and ``MuJoCoRobot`` sim2sim -- work on the WELDED model
  produced by :func:`build_welded_xml`:

  - the 24 finger joints (:data:`FINGER_JOINT_NAMES`) are removed, welding
    each finger rigidly to the hand at the zero pose (hand mass and visuals
    are kept, so arm dynamics still feel the real hands);
  - the 26 hand collision geoms (hand base + finger hulls) are removed, so
    the hands never generate contacts;
  - each foot hull is moved onto a near-massless welded
    ``sensor_{side}_foot_fts`` body (the G3.1 model's foot FTS mount) and
    renamed ``{side}_foot_collision``; this name is only consumed through
    :data:`FOOT_CONTACT_GEOM_REGEX` (collision cfg priority/friction and the
    env's foot-friction randomization) -- G3.1 itself keeps its sole-pad and
    FTS-box geom names;
  - the 63-wide ``<keyframe>`` is dropped (it cannot compile against the
    39-DOF model; the standing pose lives in the constants' ``INIT_STATE``).

  Result: ``nq == 39`` (:data:`FULL_QPOS_DIM`), 32 hinges in
  :data:`JOINT_NAMES` order occupying ``qpos[7:39]``, and 70 non-world bodies
  in :data:`BODY_NAMES` order.  The hinge order equals the raw export's
  actuator order and the 32-column order of the retargeted CSVs.

:func:`verify_model_contract` compiles the welded model and raises if a CAD
re-export adds, drops or reorders a body, joint or actuator; it runs on every
training (``get_spec``) and dataset-build (``compile_model``) entry.
"""

